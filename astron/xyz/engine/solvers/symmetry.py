def _unknown_candidates(ctx):
    """Colours plausibly acting as the "hole" marker."""
    cands = Counter()
    if ctx.same_shape:
        for a, b in ctx.train:
            diff = set()
            for ra, rb in zip(a, b):
                for x, y in zip(ra, rb):
                    if x != y:
                        diff.add(x)
            if len(diff) == 1:
                cands[diff.pop()] += 1
    else:
        for a, b in ctx.train:
            bh, bw = G.dims(b)
            for c in G.palette(a):
                bb = _occluded_bbox(a, c)
                if bb and (bb[2] - bb[0] + 1, bb[3] - bb[1] + 1) == (bh, bw):
                    cands[c] += 1
    got = [c for c, n in cands.items() if n == len(ctx.train)]
    if got:
        return got
    return [c for c, _n in cands.most_common(3)]


def generate(ctx):
    res = []
    cands = _unknown_candidates(ctx)
    if not cands:
        # still worth trying the task background as a hole marker
        cands = [ctx.bg]
    for u in cands[:4]:
        for strict in (True, False):
            sfx = "" if strict else "_lax"
            res.append(_h("repair#%d%s" % (u, sfx),
                          (lambda u, s: lambda g: _repair(g, u, s))(u, strict),
                          3.0 if strict else 4.0))
            res.append(_h("patch#%d%s" % (u, sfx),
                          (lambda u, s: lambda g: _patch(g, u, s))(u, strict),
                          3.2 if strict else 4.2))
        res.append(_h("repair_loose#%d" % u,
                      (lambda u: lambda g: _repair(g, u, True, 0.12))(u), 5.0))
        res.append(_h("patch_loose#%d" % u,
                      (lambda u: lambda g: _patch(g, u, True))(u), 5.2))
        # Sparse mode: complete a pattern that is not yet symmetric, where only
        # a handful of cell pairs witness each axis.  A wrongly accepted axis
        # cannot survive validation on the training pairs, so the floor can be
        # low here in a way it must not be for occlusion repair.
        for strict in (False, True):
            res.append(_h("complete#%d%s" % (u, "" if strict else "_lax"),
                          (lambda u, s: lambda g: _repair(g, u, s, 0.0, 2))(u, strict),
                          5.5 if strict else 6.0))
        res.append(_h("complete_patch#%d" % u,
                      (lambda u: lambda g: _patch(g, u, True, 0.0, 2))(u), 6.0))
        for grow in (0, 1):
            res.append(_h("complete_box#%d+%d" % (u, grow),
                          (lambda u, gr: lambda g: _repair_bounded(g, u, False, 0.0, 2, gr))(u, grow),
                          4.8 + 0.3 * grow))
            res.append(_h("complete_box_s#%d+%d" % (u, grow),
                          (lambda u, gr: lambda g: _repair_bounded(g, u, False, 0.25, 4, gr))(u, grow),
                          5.0 + 0.3 * grow))
    return res
